--  Luz Vital - complemento do script Oracle para a API Java
--  Rodar DEPOIS do script principal da disciplina de banco
--  (PACIENTE, EQUIPAMENTO, PONTO_ENERGIA, OCORRENCIA, OCORRENCIA_AUDIT).
--
--  A API Java usa exatamente as mesmas tabelas e colunas do script principal
--  e acrescenta só o que o backend precisa: usuários com papéis (JWT),
--  dono do paciente, coordenadas, idempotência, atendimentos, avisos aos
--  pontos de energia, plano de contingência gerado por IA e logout.
-- =====================================================================

-- 1. Usuários (cuidador e gestor) --------------------------------------
CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(120) NOT NULL UNIQUE,
    SENHA_HASH      VARCHAR2(100) NOT NULL,          -- BCrypt, gerado pela API
    PAPEL           VARCHAR2(20)  NOT NULL,
    TELEFONE        VARCHAR2(20),
    DATA_CADASTRO   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CHK_USU_PAPEL CHECK (PAPEL IN ('CUIDADOR', 'GESTOR'))
);

-- 2. Colunas novas nas tabelas existentes ------------------------------
ALTER TABLE PACIENTE ADD (
    ID_USUARIO  NUMBER,                -- cuidador dono do cadastro
    LATITUDE    NUMBER(9,6),
    LONGITUDE   NUMBER(9,6),
    CONSTRAINT FK_PAC_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

ALTER TABLE PONTO_ENERGIA ADD (
    LATITUDE    NUMBER(9,6),
    LONGITUDE   NUMBER(9,6)
);

-- DATA_BATERIA: quando o valor de BATERIA_INICIAL_MIN foi informado (na abertura = DATA_INICIO;
-- depois, a cada PATCH /ocorrencias/{id}/bateria). Minutos restantes = BATERIA_INICIAL_MIN - (agora - DATA_BATERIA).
ALTER TABLE OCORRENCIA ADD (
    DATA_BATERIA        DATE,
    CHAVE_IDEMPOTENCIA  VARCHAR2(100),  -- cabeçalho Idempotency-Key do app
    DATA_PRIORIZACAO    DATE,           -- preenchida pelo consumidor do evento energia.caiu
    CONSTRAINT UK_OCO_IDEMPOTENCIA UNIQUE (CHAVE_IDEMPOTENCIA)
);
UPDATE OCORRENCIA SET DATA_BATERIA = DATA_INICIO WHERE DATA_BATERIA IS NULL;
ALTER TABLE OCORRENCIA MODIFY (DATA_BATERIA DEFAULT SYSDATE NOT NULL);

-- 3. Atendimentos do gestor (uma ocorrência tem vários) -----------------
CREATE TABLE ATENDIMENTO (
    ID_ATENDIMENTO      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_OCORRENCIA       NUMBER NOT NULL,
    ID_USUARIO_GESTOR   NUMBER NOT NULL,
    ID_PONTO            NUMBER,
    TIPO_ATENDIMENTO    VARCHAR2(30) NOT NULL,
    DESCRICAO           VARCHAR2(500) NOT NULL,
    DATA_REGISTRO       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_ATD_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES OCORRENCIA(ID_OCORRENCIA),
    CONSTRAINT FK_ATD_GESTOR FOREIGN KEY (ID_USUARIO_GESTOR) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_ATD_PONTO FOREIGN KEY (ID_PONTO) REFERENCES PONTO_ENERGIA(ID_PONTO),
    CONSTRAINT CHK_ATD_TIPO CHECK (TIPO_ATENDIMENTO IN
        ('CONTATO_FAMILIA', 'GERADOR', 'RECARGA_BATERIA', 'REMOCAO', 'RELIGACAO_PRIORITARIA', 'OUTRO'))
);

-- 4. Avisos aos pontos de energia (gravados pelo consumidor do RabbitMQ) --
CREATE TABLE NOTIFICACAO_PONTO (
    ID_NOTIFICACAO  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_OCORRENCIA   NUMBER NOT NULL,
    ID_PONTO        NUMBER NOT NULL,
    DISTANCIA_KM    NUMBER(7,2),
    CRITERIO        VARCHAR2(10) NOT NULL,   -- RAIO (coordenadas) ou BAIRRO
    MENSAGEM        VARCHAR2(300) NOT NULL,
    DATA_ENVIO      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_NOT_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES OCORRENCIA(ID_OCORRENCIA),
    CONSTRAINT FK_NOT_PONTO FOREIGN KEY (ID_PONTO) REFERENCES PONTO_ENERGIA(ID_PONTO),
    CONSTRAINT UK_NOTIF_OCO_PONTO UNIQUE (ID_OCORRENCIA, ID_PONTO)
);

-- 5. Plano de contingência gerado pela IA (1 por paciente) ---------------
CREATE TABLE PLANO_CONTINGENCIA (
    ID_PLANO          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PACIENTE       NUMBER NOT NULL UNIQUE,
    STATUS            VARCHAR2(10) NOT NULL,   -- GERANDO, PRONTO, ERRO
    ORIGEM            VARCHAR2(10),            -- IA ou REGRAS
    CONTEUDO          CLOB,                    -- JSON do plano estruturado
    MODELO_IA         VARCHAR2(80),
    MENSAGEM_ERRO     VARCHAR2(300),
    DATA_SOLICITACAO  DATE NOT NULL,
    DATA_GERACAO      DATE,
    CONSTRAINT FK_PLANO_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES PACIENTE(ID_PACIENTE) ON DELETE CASCADE
);

-- 6. Tokens JWT revogados no logout -------------------------------------
CREATE TABLE TOKEN_REVOGADO (
    JTI             VARCHAR2(64) PRIMARY KEY,
    DATA_EXPIRACAO  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

COMMIT;

