-- c) TRG_UPDATE_BATERIA_PRIORIDADE: a API grava a bateria com UPDATE só das colunas alteradas
--    (@DynamicUpdate), então o gatilho dispara apenas quando a bateria muda de fato.
-- d) CPFs da carga de teste: '123.456.789-01', '987.654.321-02' e '456.789.123-03' não têm
