--    '123.456.789-09', '987.654.321-00' e '456.789.123-64'.
-- e) Com o perfil "oracle", na primeira subida a API cria os usuários de teste e associa os
--    pacientes sem dono (ID_USUARIO nulo) a cuidador@luzvital.com.
